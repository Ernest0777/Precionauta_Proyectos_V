const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('persistent accounts enforce permissions across catalog, history, redirects and Telegram', async (t) => {
  const serverFile = path.join(__dirname, '../backend/server.js');
  assert.match(fs.readFileSync(serverFile, 'utf8'), /require\.main === module/, 'importing the server must never start network jobs');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'precionauta-account-'));
  process.env.PRECIONAUTA_DB = path.join(dir, 'test.db');
  process.env.NODE_ENV = 'test';
  process.env.FRONTEND_URL = 'http://localhost:4173';
  process.env.TELEGRAM_BOT_TOKEN = '';
  // El test no carga el .env real ni credenciales de proveedores.
  const configFile = require.resolve('../backend/config/config');
  require.cache[configFile] = { id: configFile, filename: configFile, loaded: true, exports: {
    mercadoLibre: { apiBase: 'https://example.invalid' }, admin: {}, telegram: {}, affiliate: {},
    server: { port: 0, env: 'test' }, discountRange: { min: 20, max: 99 },
  } };
  const meliFile = require.resolve('../backend/api/meli-client');
  require.cache[meliFile] = { id: meliFile, filename: meliFile, loaded: true, exports: new Proxy({}, { get: () => () => { throw new Error('Mercado Libre no debe consultarse en esta prueba'); } }) };
  const fetcher = require('../backend/api/deal-fetcher');
  const history = require('../backend/db/price-history');
  const db = require('../backend/db/database');
  const now = Date.now();
  const deals = Array.from({ length: 5 }, (_, i) => ({ id: `test-${i}`, title: `Private product ${i}`, category: 'tecnologia', currentPrice: 100 + i, originalPrice: 1000, discount: 80, savings: 900, permalink: 'https://www.mercadolibre.com.mx/p/test', thumbnail: 'https://example.invalid/private.jpg' }));
  history.record(deals.slice(0, 4), now - 50 * 86400000);
  history.record(deals.slice(0, 4), now - 86400000);
  history.record(deals.slice(4), now - 1000);
  fetcher.fetchAllDeals = async () => deals;
  const app = require('../backend/server');
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => {
    server.close(); db.close();
    assert.equal(path.dirname(path.resolve(dir)), path.resolve(os.tmpdir()));
    assert.ok(path.basename(dir).startsWith('precionauta-account-'));
    fs.rmSync(dir, { recursive: true, force: true });
  });
  const access = require('../backend/api/access');
  const demo = { ...deals[0], id: 'demo-without-records', source: 'demo' };
  assert.equal(access.isLocked(demo, { delayMs: 7200000 }), false, 'demo fixtures must remain visible without a real tracking baseline');
  assert.equal(access.publicDeal(demo, { delayMs: 7200000, historyDays: 30 }).firstSeenAt, null);
  const base = `http://127.0.0.1:${server.address().port}`;
  let cookie = '';
  const request = async (route, method = 'GET', body, extra = {}) => {
    const response = await fetch(base + route, { method, redirect: 'manual', headers: { Origin: 'http://localhost:4173', 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}), ...extra }, body: body === undefined ? undefined : JSON.stringify(body) }).catch(error => { throw error.cause || error; });
    if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
    const data = (response.headers.get('content-type') || '').includes('json') ? await response.json() : null;
    return { status: response.status, data, response };
  };
  let result = await request('/api/account/session');
  assert.equal(result.data.data.access.level, 'visitor');
  assert.equal((await request('/api/deals/test-0/history')).status, 401);
  result = await request('/api/deals');
  const locked = result.data.data.find(d => d.id === 'test-4');
  assert.equal(locked.locked, true);
  for (const key of ['title', 'currentPrice', 'permalink', 'thumbnail', 'history']) assert.equal(key in locked, false);
  assert.equal((await request('/api/product/test-4')).status, 403);
  assert.equal((await request('/go/test-4')).status, 403);
  assert.equal((await request('/api/deals?season=buen-fin-2026')).data.data.length, 3);
  assert.equal((await request('/api/deals?season=unknown')).status, 400);
  assert.equal((await request('/api/account/login', 'POST', { email: 'a@example.com', password: 'some password' }, { Origin: '' })).status, 403);
  assert.equal((await request('/api/account/register', 'POST', { name: 'A', email: 'a@example.com', password: 'correct horse battery' }, { Origin: 'https://evil.invalid' })).status, 403);
  assert.equal((await request('/api/account/register', 'POST', { name: 'A', email: 'bad', password: 'short' })).status, 400);
  result = await request('/api/account/register', 'POST', { name: 'Ana', email: 'ANA@example.com', password: 'correct horse battery' });
  assert.equal(result.status, 201);
  assert.match(result.response.headers.get('set-cookie'), /HttpOnly/);
  assert.match(result.response.headers.get('set-cookie'), /SameSite=Lax/);
  assert.equal(result.data.data.user.email, 'ana@example.com');
  assert.equal(result.data.data.access.historyDays, 30);
  assert.equal(result.response.headers.get('access-control-allow-origin'), 'http://localhost:4173');
  assert.equal(result.response.headers.get('access-control-allow-credentials'), 'true');
  const userId = result.data.data.user.id;
  const stored = db.prepare('SELECT * FROM account_users WHERE id = ?').get(userId);
  assert.notEqual(stored.password_hash, 'correct horse battery');
  assert.ok(stored.password_salt);
  assert.equal((await request('/api/deals/test-0/history?days=365')).data.data.length, 1);
  result = await request('/api/deals');
  assert.equal(result.data.data[0].history.points, 1);
  assert.equal(result.data.data[0].history.days <= 30, true);
  assert.equal((await request('/api/deals/test-4/history')).status, 403);
  result = await request('/api/account/library', 'PUT', { savedIds: ['test-0', 'test-0'], alertIds: ['test-0', 'test-1', 'test-2'] });
  assert.deepEqual(result.data.data.savedIds, ['test-0']);
  assert.equal((await request('/api/account/library', 'PUT', { savedIds: [], alertIds: ['test-0', 'test-1', 'test-2', 'test-3'] })).status, 403);
  result = await request('/api/account/library', 'PUT', { savedIds: ['test-1'], alertIds: ['test-1'], merge: true });
  assert.deepEqual(result.data.data.savedIds, ['test-0', 'test-1']);
  // Both tabs operate from the same original session without replacing one another's state.
  const sharedCookie = cookie;
  result = await request('/api/account/library', 'PATCH', { savedAdd: ['tab-a'] }, { Cookie: sharedCookie });
  assert.equal(result.status, 200);
  result = await request('/api/account/library', 'PATCH', { savedAdd: ['tab-b'] }, { Cookie: sharedCookie });
  assert.ok(result.data.data.savedIds.includes('tab-a'));
  assert.ok(result.data.data.savedIds.includes('tab-b'));
  result = await request('/api/account/library', 'PATCH', { savedRemove: ['tab-a'] }, { Cookie: sharedCookie });
  assert.ok(!result.data.data.savedIds.includes('tab-a'));
  assert.ok(result.data.data.savedIds.includes('tab-b'));
  assert.equal((await request('/api/account/library', 'PATCH', { alertAdd: ['test-3'] })).status, 403);
  assert.equal((await request('/api/account/library', 'PATCH', { savedAdd: ['invalid id'] })).status, 400);
  assert.equal((await request('/api/account/library', 'PATCH', { alertRemove: 'test-0' })).status, 400);
  result = await request('/api/account/plan', 'POST', { id: 'plus', period: 'anual' });
  assert.equal(result.data.data.access.historyDays, 365);
  assert.equal((await request('/api/deals/test-0/history?days=365')).data.data.length, 2);
  assert.equal((await request('/api/deals?season=buen-fin-2026')).data.data.length, 5);
  assert.equal((await request('/api/product/test-4')).status, 200);
  assert.equal((await request('/go/test-4')).status, 302);
  await request('/api/account/library', 'PUT', { savedIds: ['test-0'], alertIds: deals.map(d => d.id) });
  await request('/api/account/profile', 'PATCH', { name: 'Ana María', address: 'CDMX' });
  assert.equal((await request('/api/telegram/link/secure-code-123', 'POST', {})).status, 200);
  db.prepare('UPDATE telegram_links SET chat_id = ? WHERE code = ?').run('fake-chat', 'secure-code-123');
  const telegram = require('../backend/db/telegram');
  assert.equal(telegram.eligibleLinks().length, 1);
  result = await request('/api/account/plan', 'POST', { id: 'free' });
  assert.equal(result.data.data.alertIds.length, 5);
  assert.equal(result.data.data.pausedAlertIds.length, 2);
  db.prepare('INSERT INTO alert_subs (code, deal_id, created_at) VALUES (?, ?, ?)').run('secure-code-123', 'test-4', Date.now());
  result = await request('/api/account/library', 'PATCH', { savedAdd: ['later'] });
  assert.equal(result.data.data.pausedAlertIds.length, 2);
  assert.equal((await request('/api/account/library', 'PATCH', { alertAdd: ['new-alert'] })).status, 403);
  result = await request('/api/account/library', 'PATCH', { alertRemove: ['test-4'] });
  assert.equal(result.data.data.alertIds.length, 4);
  assert.equal(db.prepare('SELECT COUNT(*) AS count FROM alert_subs WHERE code = ? AND deal_id = ?').get('secure-code-123', 'test-4').count, 0);
  assert.equal((await request('/api/alerts/sync', 'POST', { code: 'secure-code-123', ids: [] })).status, 403);
  assert.equal(telegram.eligibleLinks().length, 0);
  const oldCookie = cookie;
  await request('/api/account/logout', 'POST', {});
  assert.equal((await request('/api/account/session', 'GET', undefined, { Cookie: oldCookie })).data.data.user, null);
  assert.equal((await request('/api/account/login', 'POST', { email: 'ana@example.com', password: 'wrong password' })).status, 401);
  result = await request('/api/account/login', 'POST', { email: 'ana@example.com', password: 'correct horse battery' });
  assert.equal(result.data.data.user.name, 'Ana María');
  assert.equal(result.data.data.user.address, 'CDMX');
  assert.equal(result.data.data.alertIds.length, 4);
  const firstAccountCookie = cookie;
  cookie = ''; // Otro navegador: cambiar de cuenta en uno mismo revoca la sesión anterior.
  result = await request('/api/account/register', 'POST', { name: 'Bea', email: 'bea@example.com', password: 'another secure password' });
  assert.deepEqual(result.data.data.savedIds, []);
  assert.equal((await request('/api/telegram/link/secure-code-123', 'POST', {})).status, 403);
  await request('/api/account/plan', 'POST', { id: 'plus', period: 'mensual' });
  assert.equal((await request('/api/telegram/link/secure-code-123', 'POST', {})).status, 403);
  assert.equal((await request('/api/telegram/link/secure-code-123')).data.data.linked, false);
  await request('/api/telegram/link/secure-code-123', 'DELETE');
  assert.equal(db.prepare('SELECT chat_id FROM telegram_links WHERE code = ?').get('secure-code-123').chat_id, 'fake-chat');
  await request('/api/account/plan', 'POST', { id: 'free' });
  result = await request('/api/account/library', 'PUT', { savedIds: ['test-2'], alertIds: ['test-0', 'test-1', 'test-2', 'test-3'], merge: true });
  assert.equal(result.data.data.alertIds.length, 4);
  assert.equal(result.data.data.pausedAlertIds.length, 1);
  const maxSaved = Array.from({ length: 2000 }, (_, i) => `saved-${i}`);
  result = await request('/api/account/library', 'PUT', { savedIds: maxSaved, alertIds: result.data.data.alertIds });
  assert.equal(result.status, 200);
  assert.equal((await request('/api/account/library', 'PATCH', { savedAdd: ['overflow'] })).status, 400);
  assert.equal((await request('/api/account/library', 'PATCH', { savedRemove: [...maxSaved, 'overflow'] })).status, 400);
  assert.equal((await request('/api/account/session')).data.data.savedIds.length, 2000);
  const expiredCookie = cookie;
  db.prepare('UPDATE account_sessions SET expires_at = 0 WHERE user_id = ?').run(result.data.data.user.id);
  assert.equal((await request('/api/account/session', 'GET', undefined, { Cookie: expiredCookie })).data.data.user, null);
  cookie = firstAccountCookie;
  process.env.NODE_ENV = 'production';
  assert.equal((await request('/api/account/plan', 'POST', { id: 'plus', period: 'mensual' })).status, 403);
  process.env.NODE_ENV = 'test';
  for (let i = 0; i < 20; i++) result = await request('/api/account/login', 'POST', { email: 'nobody@example.com', password: 'wrong password' });
  assert.equal(result.status, 429);
});
